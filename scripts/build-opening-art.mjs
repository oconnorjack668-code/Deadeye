// Writes src/components/brand/openingArt.ts: the pieces of logo C that the
// opening animation moves (four ball layers, four corner brackets, the
// wordmark), as static SVG strings, from the designer's logo lib.
//   node scripts/build-opening-art.mjs
// Re-run only when the logo changes. The ball is four stacked layers so the
// seams can turn (opening B's backspin) while the lighting stays put; at rest
// the stack is the logo ball itself (docs/agent-os/design/2026-11-22-loading.md).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { VARIANTS, ballInner, bracketPath, WORD } from '../docs/agent-os/design/logo/2026-11-22-logo-lib.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const v = VARIANTS['improved-c'];
const r = v.R;
const box = `viewBox="${v.cx - r} ${v.cy - r} ${r * 2} ${r * 2}" aria-hidden="true" focusable="false"`;
// One id prefix per layer, so no two elements on the page share an id
const layer = (name) => `<svg ${box}>${ballInner(v, `ddo${name[0]}`, false, name).replace(/\s*\n\s*/g, '')}</svg>`;
const corner = (sx, sy, i) =>
  `<svg viewBox="0 0 ${v.arm} ${v.arm}" aria-hidden="true" focusable="false"><defs><linearGradient id="ddok${i}" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="${v.bracket[0]}"/><stop offset="1" stop-color="${v.bracket[1]}"/></linearGradient></defs><path d="${bracketPath(v, sx, sy, true)}" fill="url(#ddok${i})"/></svg>`;
const word = `<svg viewBox="237 804 553 102" aria-hidden="true" focusable="false"><g fill="#f4f4f5">${WORD.map((d) => `<path d="${d}"/>`).join('')}</g></svg>`;

// Sizes on the 390 x 844 stage the prototypes were drawn on (scale 0.385 of the 1024 logo)
const s = 0.385;
const geo = {
  scope: Math.round(2 * v.box * s),
  ball: Math.round(2 * v.R * s),
  arm: Math.round(v.arm * s),
  wordW: Math.round(553 * s * v.wordK),
  wordH: Math.round(102 * s * v.wordK),
  gap: Math.round((905 - 101 * v.wordK + v.wordDy - (v.cy + v.box)) * s),
};

const out = `// src/components/brand/openingArt.ts
// GENERATED by scripts/build-opening-art.mjs from logo C. Do not edit by hand.

export const OPENING_GEO = ${JSON.stringify(geo)} as const;

export const BALL_LAYERS = ${JSON.stringify({ base: layer('base'), disc: layer('disc'), dot: layer('dot'), top: layer('top') }, null, 2)} as const;

/** Top left, top right, bottom left, bottom right. */
export const CORNERS = ${JSON.stringify([corner(-1, -1, 0), corner(1, -1, 1), corner(-1, 1, 2), corner(1, 1, 3)], null, 2)} as const;

export const WORDMARK = ${JSON.stringify(word)};
`;
fs.writeFileSync(path.join(ROOT, 'src/components/brand/openingArt.ts'), out);
console.log('wrote openingArt.ts', Math.round(out.length / 1024), 'KB', geo);
